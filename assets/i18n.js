/* Apply a language to the page */
window.BJ_setLang = function (code, opts = {}) {
  const D = window.BJ_I18N, L = D[code] ? code : "en", dict = D[L], en = D.en;
  document.documentElement.lang = L;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const k = el.dataset.i18n, v = dict[k] ?? en[k];
    if (v == null) return;
    if (el.dataset.raw !== undefined || k === "about.text") { el.dataset.raw = v; el.textContent = v.replace(/\*/g, ""); }
    else el.innerHTML = v;
  });
  const t = document.body.dataset.title;
  if (t && dict[t]) document.title = dict[t];
  try { localStorage.setItem("bj-lang", L); } catch {}
  if (!opts.silent) document.dispatchEvent(new CustomEvent("bj:lang", { detail: L }));
  return L;
};

/* Pick the starting language: ?lang= → saved → browser → English */
window.BJ_initialLang = function () {
  const ok = (c) => c && window.BJ_I18N[c] ? c : null;
  const q = new URLSearchParams(location.search).get("lang");
  let saved = null; try { saved = localStorage.getItem("bj-lang"); } catch {}
  const nav = (navigator.languages || [navigator.language || "en"]).map((l) => l.slice(0, 2).toLowerCase());
  return ok(q) || ok(saved) || nav.map(ok).find(Boolean) || "en";
};
