#!/usr/bin/env python3
"""Generates assets/map-data.js: a Europe-focused dotted map (projected plane) + capitals.
Uses the hand-simplified coastlines in globe_data.py."""
import json, math, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
import importlib.util
spec = importlib.util.spec_from_file_location("g", Path(__file__).parent / "globe_data.py")
src = (Path(__file__).parent / "globe_data.py").read_text().split("dots = []")[0]
ns = {}; exec(src, ns)
land, CAPITALS, CONTACT = ns["land"], ns["CAPITALS"], ns["CONTACT"]
LON0, LAT0 = 18.0, 50.0
K = math.cos(math.radians(LAT0))
def P(lon, lat):  # simple conic-like projection, map units = degrees of latitude
    return ((lon - LON0) * K * (1 + 0.004 * (LAT0 - lat)), lat - LAT0)
def Pinv(x, y):
    lat = y + LAT0; return (x / (K * (1 + 0.004 * (LAT0 - lat))) + LON0, lat)
dots = []; step = 0.42
y = -24.0
row = 0
while y <= 22.0:
    x = -26.0 + (step / 2 if row % 2 else 0)
    while x <= 28.0:
        lon, lat = Pinv(x, y)
        if land(lon, lat): dots += [round(x, 2), round(y, 2)]
        x += step
    y += step * 0.866; row += 1
caps = [[n, *[round(v, 3) for v in P(lo, la)], 1 if n in CONTACT else 0] for n, la, lo in CAPITALS]
out = Path(__file__).resolve().parent.parent / "assets" / "map-data.js"
out.write_text("/* generated by tools/map_data.py */\nwindow.BJ_MAP={dots:" + json.dumps(dots, separators=(",", ":")) +
               ",caps:" + json.dumps(caps, ensure_ascii=False, separators=(",", ":")) + "};\n")
print(len(dots)//2, "dots", out.stat().st_size//1024, "KB")
from PIL import Image, ImageDraw
im = Image.new("RGB", (1080, 920), "black"); d = ImageDraw.Draw(im)
for i in range(0, len(dots), 2):
    X = (dots[i] + 27) * 20; Y = (23 - dots[i+1]) * 20; d.ellipse((X-2, Y-2, X+2, Y+2), fill="white")
for n, x, y, c in caps:
    X = (x + 27) * 20; Y = (23 - y) * 20; d.ellipse((X-4, Y-4, X+4, Y+4), fill=(255,200,0) if not c else (80,160,255))
im.save("/home/claude/shots/mapcheck.png")
